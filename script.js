window.updateGoal =
function(id, amount) {

    const goal =
        goals.find(
            goal =>
                goal.id === id
        );


    if (!goal) return;


    goal.current =
        Math.max(
            0,
            Math.min(
                goal.target,
                goal.current + amount
            )
        );


    saveAll();

    renderGoals();

    updateDashboard();

};

