function setLanguage(language) {

    currentLanguage =
        language;

    localStorage.setItem(
        "hubLanguage",
        language
    );


    document.documentElement.lang =
        language;


    document.documentElement.dir =
        language === "ar"
        ? "rtl"
        : "ltr";


    const dictionary =
        translations[language];


    document
        .querySelectorAll("[data-i18n]")
        .forEach(element => {

            const key =
                element.dataset.i18n;

            if (dictionary[key]) {

                element.textContent =
                    dictionary[key];

            }

        });


    document
        .querySelectorAll("[data-placeholder]")
        .forEach(element => {

            const key =
                element.dataset.placeholder;

            if (dictionary[key]) {

                element.placeholder =
                    dictionary[key];

            }

        });


    updatePageLanguage();

    renderTasks();

    renderProjects();

    renderNotes();

    renderGoals();

}


