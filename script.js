document.getElementById(
    "taskForm"
).addEventListener(
    "submit",
    event => {

        event.preventDefault();


        const title =
            document.getElementById(
                "taskName"
            ).value.trim();


        if (!title) {

            showToast(
                "⚠️",
                "Please enter a task name."
            );

            return;

        }


        const taskData = {

            title,

            description:
                document.getElementById(
                    "taskDescription"
                ).value.trim(),

            priority:
                document.getElementById(
                    "taskPriority"
                ).value,

            date:
                document.getElementById(
                    "taskDate"
                ).value

        };


        if (editingTaskId) {

            const task =
                tasks.find(
                    task =>
                        task.id ===
                        editingTaskId
                );


            if (task) {

                Object.assign(
                    task,
                    taskData
                );

            }

        } else {

            tasks.push({

                id: Date.now(),

                ...taskData,

                status: "todo",

                createdAt:
                    new Date().toISOString()

            });

        }


        saveAll();

        renderTasks();

        closeModal("taskModal");

        event.target.reset();

        showToast(
            "✓",
            editingTaskId
            ? "Task updated."
            : "Task created."
        );


        editingTaskId = null;

    }
);


function renderTasks() {

    const containers = {

        todo:
            document.getElementById(
                "todoContainer"
            ),

        progress:
            document.getElementById(
                "progressContainer"
            ),

        done:
            document.getElementById(
                "doneContainer"
            )

    };


    Object.values(containers)
        .forEach(container => {

            container.innerHTML = "";

        });


    const search =
        document.getElementById(
            "taskSearch"
        ).value.toLowerCase();


    const filter =
        document.getElementById(
            "priorityFilter"
        ).value;


    const filtered =
        tasks.filter(task => {

            const matchesSearch =
                task.title
                    .toLowerCase()
                    .includes(search);


            const matchesPriority =
                filter === "all"
                ||
                task.priority === filter;


            return (
                matchesSearch
                &&
                matchesPriority
            );

        });


    filtered.forEach(task => {

        const card =
            createTaskCard(task);


        containers[
            task.status
        ].appendChild(card);

    });


    updateTaskCounts();

    updateDashboard();

}


function createTaskCard(task) {

    const card =
        document.createElement("article");


    card.className =
        "task-card";


    card.draggable = true;


    card.dataset.id =
        task.id;


    const priorityText =
        translations[currentLanguage]
        [task.priority];


    card.innerHTML = `

        <h4>
            ${escapeHTML(task.title)}
        </h4>

        <p>
            ${escapeHTML(
                task.description
                || "No description"
            )}
        </p>

        <div class="task-card-bottom">

            <span class="priority ${task.priority}">
                ${priorityText}
            </span>

            <span class="task-date">
                ${
                    task.date
                    ? "📅 " + task.date
                    : ""
                }
            </span>

        </div>


        <div class="task-actions">

            <button
                title="Edit"
                onclick="editTask(${task.id})">
                ✎
            </button>

            <button
                title="Complete"
                onclick="completeTask(${task.id})">
                ✓
            </button>

            <button
                title="Delete"
                onclick="deleteTask(${task.id})">
                ×
            </button>

        </div>

    `;


    card.addEventListener(
        "dragstart",
        event => {

            card.classList.add(
                "dragging"
            );

            event.dataTransfer.setData(
                "text/plain",
                task.id
            );

        }
    );


    card.addEventListener(
        "dragend",
        () => {

            card.classList.remove(
                "dragging"
            );

        }
    );


    return card;

}


document
    .querySelectorAll(".kanban-column")
    .forEach(column => {

        column.addEventListener(
            "dragover",
            event => {

                event.preventDefault();

                column.classList.add(
                    "drag-over"
                );

            }
        );


        column.addEventListener(
            "dragleave",
            () => {

                column.classList.remove(
                    "drag-over"
                );

            }
        );


        column.addEventListener(
            "drop",
            event => {

                event.preventDefault();


                column.classList.remove(
                    "drag-over"
                );


                const id =
                    Number(
                        event.dataTransfer
                            .getData(
                                "text/plain"
                            )
                    );


                const task =
                    tasks.find(
                        task =>
                            task.id === id
                    );


                if (!task) return;


                task.status =
                    column.dataset.status;


                saveAll();

                renderTasks();

                showToast(
                    "↔",
                    "Task moved."
                );

            }
        );

    });

window.editTask =
function(id) {

    const task =
        tasks.find(
            task =>
                task.id === id
        );


    if (task) {

        openTaskModal(task);

    }

};


window.completeTask =
function(id) {

    const task =
        tasks.find(
            task =>
                task.id === id
        );


    if (!task) return;


    task.status =
        task.status === "done"
        ? "todo"
        : "done";


    saveAll();

    renderTasks();

    showToast(
        "✓",
        task.status === "done"
        ? "Task completed!"
        : "Task moved back."
    );

};


window.deleteTask =
function(id) {

    tasks =
        tasks.filter(
            task =>
                task.id !== id
        );


    saveAll();

    renderTasks();

    showToast(
        "×",
        "Task deleted."
    );

};


