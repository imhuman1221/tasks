function startTimer() {

    timerRunning =
        true;


    document.getElementById(
        "timerStart"
    ).innerHTML =
        "❚❚ Pause";


    timerInterval =
        setInterval(
            () => {

                if (
                    timerSeconds <= 0
                ) {

                    stopTimer();

                    showToast(
                        "🎉",
                        "Focus session complete!"
                    );

                    return;

                }


                timerSeconds--;

                updateTimerDisplay();

            },
            1000
        );

}


function stopTimer() {

    timerRunning =
        false;


    clearInterval(
        timerInterval
    );


    document.getElementById(
        "timerStart"
    ).innerHTML =
        `▶ <span>Start</span>`;

}


